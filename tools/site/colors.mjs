// Writes docs/colors.css: a Material 3 tonal-spot scheme (Android's default dynamic scheme) for each
// wallpaper seed, light and dark, as CSS custom properties under [data-seed="<id>"]. The bar's roles
// (--bar-*) come straight from the tonal palettes at the tones values-v31 maps them to, so the
// page's bar matches the app on that wallpaper.
//
//   cd tools/site && npm install && node colors.mjs
import { writeFileSync } from 'node:fs'
import { argbFromHex, hexFromArgb, Hct, SchemeTonalSpot, MaterialDynamicColors as C } from '@material/material-color-utilities'

// The first seed is the default: it gives primary #415F91, the app's fixed palette before Android 12.
export const SEEDS = [
  { id: 'blue', name: 'Voicebar blue', hex: '#769CDF' },
  { id: 'moss', name: 'Moss', hex: '#6B8F4E' },
  { id: 'clay', name: 'Clay', hex: '#C26B4A' },
  { id: 'orchid', name: 'Orchid', hex: '#9B6FB5' },
  { id: 'lagoon', name: 'Lagoon', hex: '#3E9A9A' },
  { id: 'rose', name: 'Rose', hex: '#C9607E' },
]

const ROLES = ['primary', 'onPrimary', 'primaryContainer', 'onPrimaryContainer', 'secondary', 'onSecondary',
  'secondaryContainer', 'onSecondaryContainer', 'tertiary', 'onTertiary', 'tertiaryContainer', 'onTertiaryContainer',
  'error', 'onError', 'errorContainer', 'onErrorContainer', 'surface', 'onSurface', 'onSurfaceVariant',
  'surfaceDim', 'surfaceBright', 'surfaceContainerLowest', 'surfaceContainerLow', 'surfaceContainer',
  'surfaceContainerHigh', 'surfaceContainerHighest', 'inverseSurface', 'inverseOnSurface', 'inversePrimary',
  'outline', 'outlineVariant', 'primaryFixed', 'primaryFixedDim', 'tertiaryFixed', 'onTertiaryFixed']

// Android's system_<palette>_<n> → tone: 0→100, 10→99, 50→95, 100→90 … 900→10.
const tone = n => n === 0 ? 100 : n === 10 ? 99 : n === 50 ? 95 : 100 - n / 10
// values-v31 / values-night-v31 colors.xml, role by role (error colors are fixed there too).
const BAR = {
  light: { surface: ['n1', 100], key: ['n2', 200], onKey: ['n2', 700], secondary: ['a2', 100], onSecondary: ['a2', 900],
    tertiary: ['a3', 100], onTertiary: ['a3', 900], primaryContainer: ['a1', 100], onPrimaryContainer: ['a1', 900],
    primary: ['a1', 600], onPrimary: ['a1', 0], bright: ['n1', 10], onBright: ['n1', 900], nav: ['n1', 50] },
  dark: { surface: ['n1', 900], key: ['n2', 700], onKey: ['n2', 200], secondary: ['a2', 700], onSecondary: ['a2', 100],
    tertiary: ['a3', 700], onTertiary: ['a3', 100], primaryContainer: ['a1', 700], onPrimaryContainer: ['a1', 100],
    primary: ['a1', 200], onPrimary: ['a1', 800], bright: ['n1', 800], onBright: ['n1', 100], nav: ['n1', 900] },
}

const kebab = s => s.replace(/[A-Z]/g, c => '-' + c.toLowerCase())

function block(seed, dark) {
  const s = new SchemeTonalSpot(Hct.fromInt(argbFromHex(seed.hex)), dark, 0)
  const palettes = { a1: s.primaryPalette, a2: s.secondaryPalette, a3: s.tertiaryPalette, n1: s.neutralPalette, n2: s.neutralVariantPalette }
  const out = ROLES.map(r => `--md-${kebab(r)}:${hexFromArgb(C[r].getArgb(s))}`)
  for (const [role, [p, n]] of Object.entries(BAR[dark ? 'dark' : 'light']))
    out.push(`--bar-${kebab(role)}:${hexFromArgb(palettes[p].tone(tone(n)))}`)
  return out.join(';')
}

// The swatch: Android's wallpaper-colors circle (primary on top, secondary and tertiary below).
function swatch(seed) {
  const s = new SchemeTonalSpot(Hct.fromInt(argbFromHex(seed.hex)), false, 0)
  return [s.primaryPalette.tone(80), s.secondaryPalette.tone(80), s.tertiaryPalette.tone(70)].map(hexFromArgb)
}

let css = '/* Generated by tools/site/colors.mjs: do not edit. Material 3 tonal-spot schemes per wallpaper seed. */\n'
for (const seed of SEEDS) {
  const sel = `[data-seed="${seed.id}"]`
  const def = seed === SEEDS[0] ? ':root,' : ''
  css += `${def}:root${sel}{${block(seed, false)}}\n`
  css += `@media (prefers-color-scheme:dark){${def.replace(',', ':not([data-theme="light"]),')}:root${sel}:not([data-theme="light"]){${block(seed, true)}}}\n`
  css += `:root${sel}[data-theme="dark"]{${block(seed, true)}}\n`
  const [a, b, c] = swatch(seed)
  css += `.swatch[data-seed="${seed.id}"]{--sw-a:${a};--sw-b:${b};--sw-c:${c}}\n`
}
writeFileSync(new URL('../../docs/colors.css', import.meta.url), css)
console.log(`docs/colors.css: ${SEEDS.length} seeds, ${css.length} bytes`)
